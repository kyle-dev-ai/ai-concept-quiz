/**
 * 답이 열리기 직전 마지막 초를 소리로 알린다.
 *
 * 학습을 막는 요소가 아니라 거들기만 하므로, 소리를 낼 수 없는 환경에서는
 * 조용히 넘어가야 한다.
 */
export interface CountdownCue {
  /**
   * 오디오를 미리 깨워둔다.
   * 브라우저는 사용자 조작 안에서만 오디오 시작을 허용하므로,
   * 학습을 시작하는 클릭 핸들러에서 불러야 한다.
   */
  prepare(): void
  /** 남은 초를 알리는 짧은 소리. */
  tick(): void
  /** 답이 열리는 순간의 마무리 소리. */
  finish(): void
}
